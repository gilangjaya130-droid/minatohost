-- MINATOHOST BOT database
-- Jalankan sekali di Supabase SQL Editor.

create table if not exists public.bot_settings (
  user_id uuid primary key references auth.users(id) on delete cascade,
  anti_link boolean not null default false,
  welcome boolean not null default false,
  goodbye boolean not null default false,
  updated_at timestamptz not null default now()
);

create table if not exists public.bot_sessions (
  user_id uuid primary key references auth.users(id) on delete cascade,
  phone text,
  status text not null default 'disconnected',
  updated_at timestamptz not null default now()
);

create table if not exists public.bot_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  level text not null default 'info',
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.bot_settings enable row level security;
alter table public.bot_sessions enable row level security;
alter table public.bot_logs enable row level security;

drop policy if exists "Users read own bot settings" on public.bot_settings;
create policy "Users read own bot settings" on public.bot_settings
  for select using (auth.uid() = user_id);
drop policy if exists "Users insert own bot settings" on public.bot_settings;
create policy "Users insert own bot settings" on public.bot_settings
  for insert with check (auth.uid() = user_id);
drop policy if exists "Users update own bot settings" on public.bot_settings;
create policy "Users update own bot settings" on public.bot_settings
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Users read own bot session" on public.bot_sessions;
create policy "Users read own bot session" on public.bot_sessions
  for select using (auth.uid() = user_id);

drop policy if exists "Users read own logs" on public.bot_logs;
create policy "Users read own logs" on public.bot_logs
  for select using (auth.uid() = user_id);

